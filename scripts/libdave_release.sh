#!/usr/bin/env bash
# Pin gaato/dave to an official libdave C++ release.
#
#   scripts/libdave_release.sh v1.3.0/cpp
#
# Writes dave/release/libdave-<version>.js from the release's assets, removes
# the previous pin file, and points dave/build.js at the new one. Every digest
# is computed from the downloaded assets, because copying ten of them by hand
# from a release page is how a wrong one slips in. The cache tag in
# dave/src/internal/ffi/loader.c, the docs that name the release, and any C
# API change still need a manual pass: see the "Update libdave" issue that
# .github/workflows/libdave-watch.yml opens for a new release.
#
# Needs gh (authenticated), curl, sha256sum and unzip.
set -euo pipefail

if [ "$#" -ne 1 ] || [[ "$1" != v*/cpp ]]; then
  echo "usage: $0 <tag like v1.3.0/cpp>" >&2
  exit 2
fi
tag="$1"
version="${tag%/cpp}"
repository="discord/libdave"
encoded_tag="${tag//\//%2F}"

root="$(cd "$(dirname "$0")/.." && pwd)"
release_dir="$root/dave/release"
shopt -s nullglob
previous=("$release_dir"/libdave-*.js)
shopt -u nullglob
if [ "${#previous[@]}" -ne 1 ]; then
  echo "expected exactly one dave/release/libdave-*.js, found ${#previous[@]}" >&2
  exit 1
fi
output="$release_dir/libdave-$version.js"

# `commits/<ref>` resolves an annotated tag to the commit it points to.
commit="$(gh api "repos/$repository/commits/$encoded_tag" --jq .sha)"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# key, asset id, archive, library path inside the archive
assets=(
  "linux:x64 linux-x64 libdave-Linux-X64-boringssl.zip lib/libdave.so"
  "linux:arm64 linux-arm64 libdave-Linux-ARM64-boringssl.zip lib/libdave.so"
  "darwin:x64 macos-x64 libdave-macOS-X64-boringssl.zip lib/libdave.dylib"
  "darwin:arm64 macos-arm64 libdave-macOS-ARM64-boringssl.zip lib/libdave.dylib"
  "win32:x64 windows-x64 libdave-Windows-X64-boringssl.zip bin/libdave.dll"
)

entries=""
for row in "${assets[@]}"; do
  read -r key id archive library <<< "$row"
  url="https://github.com/$repository/releases/download/$encoded_tag/$archive"
  curl --proto '=https' --tlsv1.2 --fail --silent --show-error --location \
    --output "$work/$archive" "$url"
  size="$(stat -c %s "$work/$archive")"
  archive_sha="$(sha256sum "$work/$archive" | cut -d ' ' -f 1)"
  if ! unzip -l "$work/$archive" "$library" > /dev/null; then
    echo "$archive has no $library" >&2
    exit 1
  fi
  library_sha="$(unzip -p "$work/$archive" "$library" | sha256sum | cut -d ' ' -f 1)"
  entries+="    \"$key\": {
      id: \"$id\",
      archive: \"$archive\",
      archiveSize: $size,
      archiveSha256:
        \"$archive_sha\",
      libraryRelativePath: \"$library\",
      librarySha256:
        \"$library_sha\",
    },
"
done

{
  cat << EOF
"use strict";

// Generated by scripts/libdave_release.sh from the assets attached to the
// official upstream release. Keep archive and extracted-library digests
// together: the archive digest authenticates what is downloaded, while the
// library digest authenticates a preseeded extraction supplied through
// MBT_DAVE_NATIVE_ROOT.
const release = deepFreeze({
  repository: "https://github.com/$repository",
  tag: "$tag",
  commit: "$commit",
  cacheTag: "${tag//\//-}",
  releaseUrl: "https://github.com/$repository/releases/tag/$encoded_tag",
  downloadBaseUrl:
    "https://github.com/$repository/releases/download/$encoded_tag",
  assets: {
${entries}  },
});

EOF
  # The helpers below the data do not depend on the release.
  sed -n '/^function deepFreeze/,$p' "${previous[0]}"
} > "$work/release.js"

if [ "${previous[0]}" != "$output" ]; then
  rm "${previous[0]}"
fi
mv "$work/release.js" "$output"
sed -i "s|require(\"./release/libdave-[^\"]*\.js\")|require(\"./release/libdave-$version.js\")|" \
  "$root/dave/build.js"
echo "wrote ${output#"$root"/}"
